package org.teamvoided.voided_delight.data.gen.data.tags

import net.fabricmc.fabric.api.datagen.v1.FabricDataOutput
import net.fabricmc.fabric.api.datagen.v1.provider.FabricTagProvider
import net.minecraft.block.SlabBlock
import net.minecraft.block.StairsBlock
import net.minecraft.block.WallBlock
import net.minecraft.registry.HolderLookup
import net.minecraft.registry.tag.BlockTags
import org.teamvoided.voided_delight.data.tags.FDBlockTags
import org.teamvoided.voided_delight.init.VDBlocks
import org.teamvoided.voided_delight.util.*
import vectorwing.farmersdelight.common.tag.CommonTags
import vectorwing.farmersdelight.common.tag.ModTags
import java.util.concurrent.CompletableFuture
import vectorwing.farmersdelight.common.registry.ModBlocks as FDBlocks

class BlockTagProvider(output: FabricDataOutput, completableFuture: CompletableFuture<HolderLookup.Provider>) :
    FabricTagProvider.BlockTagProvider(output, completableFuture) {
    override fun configure(wrapperLookup: HolderLookup.Provider) {
        shapedBlocks()
        autoGenerated()

        getOrCreateTagBuilder(FDBlockTags.WOODEN_CABINETS)
            .add(
                FDBlocks.OAK_CABINET.get(),
                FDBlocks.SPRUCE_CABINET.get(),
                FDBlocks.BIRCH_CABINET.get(),
                FDBlocks.JUNGLE_CABINET.get(),
                FDBlocks.ACACIA_CABINET.get(),
                FDBlocks.DARK_OAK_CABINET.get(),
                FDBlocks.MANGROVE_CABINET.get(),
                FDBlocks.CHERRY_CABINET.get(),
                FDBlocks.BAMBOO_CABINET.get(),
                FDBlocks.CRIMSON_CABINET.get(),
                FDBlocks.WARPED_CABINET.get()
            )
        getOrCreateTagBuilder(FDBlockTags.CABINETS)
            .forceAddTag(FDBlockTags.WOODEN_CABINETS)

        getOrCreateTagBuilder(FDBlockTags.SKILLETS)
            .add(FDBlocks.SKILLET.get(), VDBlocks.NETHERITE_SKILLET)
        getOrCreateTagBuilder(FDBlockTags.COOKING_POTS)
            .add(FDBlocks.COOKING_POT.get(), VDBlocks.NETHERITE_COOKING_POT)
    }

    fun shapedBlocks() {
        VDBlocks.BLOCKS.forEach {
            when (it) {
                is SlabBlock -> getOrCreateTagBuilder(BlockTags.SLABS).add(it)
                is StairsBlock -> getOrCreateTagBuilder(BlockTags.STAIRS).add(it)
                is WallBlock -> getOrCreateTagBuilder(BlockTags.WALLS).add(it)
            }
        }
    }

    fun autoGenerated() {
        getOrCreateTagBuilder(BlockTags.PICKAXE_MINEABLE).addAll(PICKAXE_MINEABLE)
        getOrCreateTagBuilder(BlockTags.AXE_MINEABLE).addAll(AXE_MINEABLE)
        getOrCreateTagBuilder(BlockTags.SHOVEL_MINEABLE).addAll(SHOVEL_MINEABLE)
        getOrCreateTagBuilder(BlockTags.HOE_MINEABLE).addAll(HOE_MINEABLE)

        getOrCreateTagBuilder(ModTags.MINEABLE_WITH_KNIFE).addAll(KNIFE_MINEABLE)
        getOrCreateTagBuilder(CommonTags.MINEABLE_WITH_KNIFE).addAll(KNIFE_MINEABLE)

        getOrCreateTagBuilder(BlockTags.NEEDS_STONE_TOOL).addAll(NEEDS_STONE)
        getOrCreateTagBuilder(BlockTags.NEEDS_IRON_TOOL).addAll(NEEDS_IRON)
        getOrCreateTagBuilder(BlockTags.NEEDS_DIAMOND_TOOL).addAll(NEEDS_DIAMOND)
    }
}